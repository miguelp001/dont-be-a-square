"""
Process and optimize the 10 character backgrounds generated by NanoBanana / Imagen
Converts them to optimized WebP (quality 86) and PNG fallbacks in assets/ui/backgrounds/
"""

import os
from PIL import Image

SRC_DIR = r"C:\Users\migue\.gemini\antigravity\brain\49d0fa4a-ab33-4ff3-a4f2-68e93fc714aa"
DEST_DIR = r"d:\projects\Don't be a square\assets\ui\backgrounds"

os.makedirs(DEST_DIR, exist_ok=True)

BACKGROUND_FILES = {
    'kiri': r'kiri_workshop_bg_1794678316024.jpg',
    'mizu': r'mizu_water_garden_bg_1794678385687.jpg',
    'riff': r'riff_stage_background_png_1794678356733.jpg',
    'mocha': r'mocha_alchemy_workshop_bg_1794678356279.jpg',
    'ember': r'ember_matsuri_stage_bg_1794678352116.jpg',
    'volt': r'volt_lab_background_png_1794678350497.jpg',
    'salty': r'salty_pirate_ship_bg_1794678388869.jpg',
    'poppy': r'poppy_idol_stage_bg_1794678357911.jpg',
    'void_slime': r'void_slime_cosmic_battle_background_1794678391705.jpg',
    'nano_banana': r'nano_banana_battle_background_1794678356729.jpg'
}

for char_id, filename in BACKGROUND_FILES.items():
    src_path = os.path.join(SRC_DIR, filename)
    if not os.path.exists(src_path):
        print(f"ERROR: {src_path} not found!")
        continue

    img = Image.open(src_path).convert("RGB")
    
    # Save optimized WebP
    webp_path = os.path.join(DEST_DIR, f"bg_{char_id}.webp")
    img.save(webp_path, "WEBP", quality=86, method=6)
    
    # Save optimized PNG fallback
    png_path = os.path.join(DEST_DIR, f"bg_{char_id}.png")
    img.save(png_path, "PNG", optimize=True)
    
    webp_sz = os.path.getsize(webp_path)
    png_sz = os.path.getsize(png_path)
    print(f"Processed {char_id}: WebP={webp_sz//1024}KB, PNG={png_sz//1024}KB, size={img.size}")

print("\nAll 10 character backgrounds processed successfully!")
